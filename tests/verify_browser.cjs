// Optional local browser verification; no external site or private data is used.
const { chromium } = require(process.env.BIZINTEL_PLAYWRIGHT || 'playwright');
const path = require('path');
const fs = require('fs');
(async () => {
  const folder = path.resolve(__dirname, '..', '.verification');
  fs.mkdirSync(folder, {recursive:true});
  const browser = await chromium.launch({channel:'chrome', headless:true});
  const page = await browser.newPage({viewport:{width:1440,height:1050}});
  await page.goto('http://127.0.0.1:8510');
  await page.locator('input[type="file"]').setInputFiles(path.resolve(__dirname,'..','sample_sales.csv'));
  await page.getByText('Dataset loaded.',{exact:false}).waitFor();
  await page.getByRole('button',{name:'Use sample data',exact:true}).click();
  await page.getByText('Dataset loaded.',{exact:false}).waitFor();
  await page.getByRole('button',{name:'Open automatic dashboard',exact:true}).click();
  await page.getByText('5,180.00',{exact:true}).waitFor();
  await page.getByRole('button',{name:'Data',exact:true}).click();
  await page.locator('input[type="file"]').setInputFiles(path.resolve(__dirname,'..','sample_sales_catalogue.csv'));
  await page.getByText('Dataset loaded. 20 columns mapped',{exact:false}).waitFor();
  await page.getByRole('button',{name:'Open automatic dashboard',exact:true}).click();
  await page.getByText('Reported profit',{exact:true}).waitFor();
  await page.getByText('17.00',{exact:true}).waitFor();
  await page.locator('.js-plotly-plot').first().waitFor();
  await page.screenshot({path:path.join(folder,'dashboard-desktop.png'),fullPage:true});
  if (await page.locator('[data-testid="stException"]').count()) throw Error('Dashboard exception');
  await page.getByRole('button',{name:'Reports',exact:true}).click();
  await page.getByLabel('Your final interpretation',{exact:true}).fill('Review stock levels before a decision.');
  await page.getByText('Preview report',{exact:true}).click();
  await page.getByRole('button',{name:'Prepare HTML and PDF downloads',exact:true}).click();
  const pdfButton=page.getByRole('button',{name:'Download PDF report',exact:true});
  await pdfButton.waitFor({timeout:60000});
  const pdfDownload=page.waitForEvent('download');
  await pdfButton.click();
  await (await pdfDownload).saveAs(path.join(folder,'browser-report.pdf'));
  const htmlDownload=page.waitForEvent('download');
  await page.getByRole('button',{name:'Download HTML report',exact:true}).click();
  await (await htmlDownload).saveAs(path.join(folder,'browser-report.html'));
  await page.screenshot({path:path.join(folder,'reports-desktop.png'),fullPage:true});
  await page.setViewportSize({width:390,height:844});
  const closeSidebar=page.locator('[data-testid="stSidebarCollapseButton"] button');
  if(await closeSidebar.isVisible()) await closeSidebar.click();
  await page.waitForTimeout(600);
  await page.screenshot({path:path.join(folder,'reports-mobile.png'),fullPage:true});
  const overflow=await page.evaluate(()=>document.documentElement.scrollWidth>window.innerWidth);
  if(overflow) throw Error('Horizontal page overflow at mobile width');
  const offline=await browser.newContext({offline:true});
  const reportPage=await offline.newPage();
  await reportPage.goto('file:///'+path.join(folder,'browser-report.html').replaceAll('\\','/'));
  await reportPage.locator('.js-plotly-plot').first().waitFor();
  if(await reportPage.locator('.js-plotly-plot').count()!==3) throw Error('Offline HTML charts missing');
  await offline.close();
  console.log('PASS: real CSV upload, sample-to-dashboard, report editor, actual PDF/HTML downloads, offline HTML charts and narrow page width.');
  await browser.close();
})().catch(error=>{console.error(error);process.exit(1)});
